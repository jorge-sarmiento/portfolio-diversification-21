TOL = 1e-10
DAILY_SAMPLE = 120      # dates per universe in the diagnostics that solve two programs per date


def parse_args(description: str, extra=None) -> argparse.Namespace:
    """Common arguments; `extra` is a function that adds the arguments of one script."""
    ap = argparse.ArgumentParser(description=description)
    ap.add_argument("--run-dir", type=Path, default=C.RESULTS_DIR / "main")
    ap.add_argument("--out", type=Path, default=None, help="default: <run-dir>/diagnostics")
    ap.add_argument("--workers", type=int, default=0, help="0 = number of physical CPU cores")
    if extra is not None:
        extra(ap)
    a = ap.parse_args()
    if a.workers <= 0:
        from src.runner import physical_cores
        a.workers = physical_cores()
    a.run_dir = a.run_dir.resolve()
    a.out = (a.out or a.run_dir / "diagnostics").resolve()
    a.out.mkdir(parents=True, exist_ok=True)
    return a


def panel(universe: str, freq: str):
    """Returns, risk-free rate and schedule of a task."""
    rets, rf = load_panel(universe, freq)
    return rets, rf, schedule_indices(rets.index, freq)


def moments(window: np.ndarray, ppy: int):
    """Annualised mean and Ledoit-Wolf covariance of a window, as in the engine."""
    return window.mean(axis=0) * ppy, LedoitWolf().fit(window).covariance_ * ppy


def sharpe(x: np.ndarray, ppy: int) -> float:
    return float(x.mean() * ppy / (x.std(ddof=1) * np.sqrt(ppy) + 1e-10))


def sample(idx: np.ndarray, freq: str) -> np.ndarray:
    """Every monthly date; DAILY_SAMPLE evenly spaced daily dates."""
    if freq == "MONTHLY":
        return idx
    return idx[np.unique(np.linspace(0, len(idx) - 1, DAILY_SAMPLE).astype(int))]


def pool_map(fn, jobs, workers: int):
    if workers <= 1:
        return [fn(j) for j in jobs]
    with ProcessPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(fn, jobs))


def selected(run_dir: Path, universe: str, freq: str, code: str) -> pd.Series:
    """Hyperparameters selected in the run for a strategy."""
    return pd.read_csv(run_dir / universe / freq / "best_params.csv").set_index("Strategy").loc[code]


def table_helpers():
    """The LaTeX helpers of scripts/tables/_common.py (loaded under another name: both files are _common)."""
    import importlib.util
    name = "_tables_common"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / "tables" / "_common.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def write_tex(path: Path, *args, **kwargs) -> None:
    """write_table of scripts/tables, with the header line naming this folder."""
    table_helpers().write_table(path, *args, **kwargs)
    text = path.read_text(encoding="utf-8")
    path.write_text(text.replace("% Generated by scripts/tables/", "% Generated by scripts/diagnostics/", 1),
                    encoding="utf-8")
