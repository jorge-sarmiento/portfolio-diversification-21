def parse_args(description: str, freq: bool = False) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=description)
    ap.add_argument("--run-dir", type=Path, default=C.RESULTS_DIR / "main")
    ap.add_argument("--out", type=Path, default=None, help="default: <run-dir>/latex")
    if freq:
        ap.add_argument("--freq", choices=C.FREQS, default="MONTHLY")
    a = ap.parse_args()
    a.run_dir = a.run_dir.resolve()
    a.out = (a.out or a.run_dir / "latex").resolve()
    a.out.mkdir(parents=True, exist_ok=True)
    return a


def universes(columns: Iterable[str]) -> List[str]:
    cols = set(columns)
    return [u for u in C.UNIVERSES if u in cols]


def strategies(index: Iterable[str]) -> List[str]:
    idx = set(index)
    return [s for s in ORDER if s in idx]


def num(x, nd: int = 3, plus: bool = False) -> str:
    """Number for a table cell; '--' for missing values."""
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    s = f"{x:+.{nd}f}" if plus else f"{x:.{nd}f}"
    return s.replace("-", "$-$")


def write_table(path: Path, caption: str, label: str, header: Sequence[str],
                rows: Sequence[Sequence[str]], colspec: Optional[str] = None,
                note: Optional[str] = None, top: Optional[str] = None, small: bool = True) -> None:
    """
    Write a booktabs table. A row given as a plain string is inserted verbatim
    (panel titles, \\midrule, ...).
    """
    colspec = colspec or "l" + "r" * (len(header) - 1)
    lines = [r"% Generated by scripts/tables/" + Path(sys.argv[0]).name
             + " -- do not edit by hand",
             r"\begin{table}[H]", r"\caption{" + caption + r"\label{" + label + "}}",
             r"\centering"]
    if small:
        lines.append(r"\small")
    lines += [r"\begin{tabular}{" + colspec + "}", r"\toprule"]
    if top:
        lines.append(top)
    lines += [" & ".join(header) + r" \\", r"\midrule"]
    for r in rows:
        lines.append(r if isinstance(r, str) else " & ".join(r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    if note:
        lines.append(r"\\[2pt] \footnotesize{\textit{Note.} " + note + "}")
    lines.append(r"\end{table}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path}")


def matrix_rows(df: pd.DataFrame, nd: int = 3, plus: bool = False) -> List[List[str]]:
    """Strategy rows x universe columns, with the manuscript labels."""
    cols = universes(df.columns)
    return [[PAPER_NAME[s]] + [num(df.loc[s, u], nd, plus) for u in cols] for s in strategies(df.index)]


def panel(title: str, ncols: int) -> str:
    return r"\multicolumn{" + str(ncols) + r"}{l}{\textit{" + title + r"}} \\"
